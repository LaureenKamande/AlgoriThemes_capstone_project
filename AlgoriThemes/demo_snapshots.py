"""Trusted, precomputed AlgoriThemes demo results.

Demo snapshots are generated by the existing live analytical pipeline and
committed alongside the app. Only load snapshots created by your own project:
pickle is unsafe for untrusted files.
"""
from __future__ import annotations

import gzip
import os
import pickle
import tempfile
from datetime import datetime, timezone
from pathlib import Path

SNAPSHOT_VERSION = 1
SNAPSHOT_DIR = Path(__file__).resolve().parent / "demo_snapshots"
ROUTES = {"topic", "sentiment"}

# All state required by the existing Results tabs and download functions.
SNAPSHOT_STATE_KEYS = (
    "raw_df",
    "dataset_name",
    "sheet_name",
    "working_df",
    "model_df",
    "short_df",
    "prep_summary",
    "response_column",
    "id_column",
    "survey_question",
    "duplicate_policy",
    "analysis_type",
    "analysis_results",
    "recommendations",
    "recommendation_evidence",
    "recommendation_error",
)


def build_mode() -> bool:
    """Explicit opt-in: generate/overwrite snapshots with real live results."""
    return os.getenv("ALGORITHEMES_BUILD_DEMO_SNAPSHOTS", "").strip().lower() in {
        "1", "true", "yes"
    }


def snapshot_path(route: str) -> Path:
    if route not in ROUTES:
        raise ValueError(f"Unsupported demo route: {route!r}")
    return SNAPSHOT_DIR / f"{route}.pkl.gz"


def save_demo_snapshot(route: str, session_state) -> Path:
    """Save complete, already-computed results; omit the heavyweight BERTopic model.

    Model objects are not used by Results, Response Explorer, report, or exports.
    """
    path = snapshot_path(route)
    state = {key: session_state.get(key) for key in SNAPSHOT_STATE_KEYS}
    if state["analysis_type"] != route or state["analysis_results"] is None:
        raise ValueError("No completed analysis exists for the selected demo route.")
    state["analysis_results"] = {
        key: value for key, value in state["analysis_results"].items()
        if key != "model"
    }
    payload = {
        "version": SNAPSHOT_VERSION,
        "route": route,
        "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "state": state,
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    # Atomic replacement prevents a failed write leaving a partial snapshot.
    fd, temporary = tempfile.mkstemp(prefix=f".{route}-", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as output:
            with gzip.GzipFile(fileobj=output, mode="wb", compresslevel=6) as zipped:
                pickle.dump(payload, zipped, protocol=pickle.HIGHEST_PROTOCOL)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return path


def load_demo_snapshot(route: str):
    """Load a trusted, repository-owned snapshot, or return None if absent."""
    path = snapshot_path(route)
    if not path.is_file():
        return None
    # Only load snapshot files you created and trust. Never accept uploads here.
    with gzip.open(path, "rb") as zipped:
        payload = pickle.load(zipped)
    if not isinstance(payload, dict):
        raise ValueError("Invalid demo snapshot format.")
    if payload.get("version") != SNAPSHOT_VERSION or payload.get("route") != route:
        raise ValueError("Demo snapshot is outdated or belongs to another route.")
    state = payload.get("state")
    if not isinstance(state, dict) or not all(key in state for key in SNAPSHOT_STATE_KEYS):
        raise ValueError("Demo snapshot is missing required result data.")
    if state["analysis_type"] != route or not isinstance(state["analysis_results"], dict):
        raise ValueError("Demo snapshot does not contain the expected analysis.")
    return payload
